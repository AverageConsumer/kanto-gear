"""Generate shared, one-character Latin case mappings from Python's Unicode data."""

from pathlib import Path
import unicodedata

ROOT = Path(__file__).resolve().parents[1]


def generate() -> str:
    tables = {"lower": [], "upper": []}
    for code in range(128, 0x110000):
        char = chr(code)
        if "LATIN" not in unicodedata.name(char, ""):
            continue
        for name, entries in tables.items():
            if not (char.isupper() if name == "lower" else char.islower()):
                continue
            mapped = getattr(char, name)()
            # Display fitting maps glyph positions back to the original text.
            # Expanding a character here would break that contract.
            if mapped != char and len(mapped) == 1:
                entries.append(f'["{char}"] = "{mapped}"')
    lines = [
        "-- Generated by tools/generate_latin_case.py; Unicode " + unicodedata.unidata_version + ".",
        "-- Shared by classic normalization and DS lettering. No transliteration.",
        "return function() return {",
    ]
    for name, entries in tables.items():
        lines.append(f"  {name} = {{")
        for index in range(0, len(entries), 6):
            lines.append("    " + ", ".join(entries[index:index + 6]) + ",")
        lines.append("  },")
    return "\n".join(lines + ["} end", ""])


if __name__ == "__main__":
    (ROOT / "mod/kanto_gear/i18n/latin_case.lua").write_text(
        generate(), encoding="utf-8", newline="\n"
    )
